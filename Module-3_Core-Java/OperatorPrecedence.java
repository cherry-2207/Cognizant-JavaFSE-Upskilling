public class OperatorPrecedence {
    public static void main(String[] args) {
        int result = 10 + 5 * 2;
        System.out.println(result);
        /*
        * Order of Evaluation
        * Follows BODMAS principle
        * B -> Bracket
        * D -> Division operator (/)
        * M -> Multiplication operator (*)
        * A -> Addition operator (+)
        * S -> Subtraction operator (-)
        */
    }
}
