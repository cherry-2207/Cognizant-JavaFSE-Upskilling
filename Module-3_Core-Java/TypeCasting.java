public class TypeCasting {
    public static void main(String[] args) {
        int n = 5;
        double pi = 3.14159265359;
        int num_pi = (int)pi;
        double double_n = (double)n;
        System.out.println("Integer form of double: " + num_pi);
        System.out.println("Decimal form of integer: " + double_n);
    }
}
